import { test, expect } from '@playwright/test';
test('미션 5개 → 파일 제출 → 알림 → 교사 검토 → 파일 다운로드와 새로고침', async ({ page, context }) => {
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'오늘의 작은 도전, 나만의 주행으로.'})).toBeVisible();
  await page.screenshot({path:'/tmp/hamster-student.png',fullPage:true});
  const teacher = await context.newPage();
  await teacher.goto('/'); await teacher.getByRole('button',{name:'교사 대시보드'}).click();
  await teacher.getByRole('button',{name:'시험 시작',exact:true}).click();
  await page.bringToFront();
  await expect(page.getByText('시험 진행 중',{exact:true})).toBeVisible();
  await page.getByLabel('엔트리에서 로봇 연결 확인').check();
  await page.getByLabel('안전한 공간과 정지 방법 확인').check();
  await page.getByRole('button',{name:'준비 완료',exact:true}).click();
  const titles=['5초 앞으로 가기','장애물 앞에서 멈추기','검은 선 따라가기','보자기를 보면 정지!','나만의 통합 주행'];
  for(const title of titles){
    await page.getByRole('button').filter({hasText:title}).first().click();
    await page.getByRole('button',{name:'미션 시작하기'}).click();
    await expect(page.locator('#complete-form')).toBeVisible();
    const checkboxes = page.locator('#complete-form input[type=checkbox]');
    expect(await checkboxes.count()).toBeGreaterThan(0);
    for(const box of await checkboxes.all()) await box.check();
    await page.locator('#experiment-note').fill('실제 로봇 검증이 아닌 체험 기록입니다.');
    await page.getByRole('button',{name:'미션 완료 요청'}).click();
    await expect(page.locator('.saved-record')).toBeVisible();
  }
  await page.locator('#entry-file').setInputFiles({name:'test.ent',mimeType:'application/octet-stream',buffer:Buffer.from('demo project bytes')});
  await page.locator('#final-note').fill('통합 미션을 마쳤어요.');
  await page.getByRole('button',{name:'선생님께 최종 제출'}).click();
  await expect(page.getByText('제출 완료 · 교사 확인 대기',{exact:true})).toBeVisible();
  await expect(teacher.locator('.notification-count')).toHaveText('1');
  await expect(teacher.locator('.teacher-submission h3')).toHaveText('test.ent');
  await teacher.bringToFront();
  const downloadPromise=teacher.waitForEvent('download');
  await teacher.getByRole('button',{name:'파일 다운로드 ↓',exact:true}).click();
  const download=await downloadPromise;
  expect(download.suggestedFilename()).toBe('test.ent');
  const chunks=[]; for await(const chunk of await download.createReadStream()) chunks.push(chunk);
  expect(Buffer.concat(chunks).toString()).toBe('demo project bytes');
  await teacher.getByRole('button',{name:'알림 읽음 처리'}).click();
  await expect(teacher.locator('.notification-count')).toHaveCount(0);
  await teacher.locator('#file-review select').selectOption('complete');
  await teacher.locator('#file-review textarea').fill('프로젝트 파일을 검토했습니다.');
  await teacher.getByRole('button',{name:'파일 검토 저장'}).click();
  await expect(page.getByText('파일 확인 완료',{exact:true})).toBeVisible();
  await teacher.screenshot({path:'/tmp/hamster-teacher.png',fullPage:true});
  await page.bringToFront();
  await page.reload(); await expect(page.getByText('파일 확인 완료',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
test('모바일에서 화면이 넘치지 않고 미션을 선택할 수 있다',async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto('/');
  await expect(page.getByRole('heading',{name:'오늘의 작은 도전, 나만의 주행으로.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button').filter({hasText:'검은 선 따라가기'}).click();
  await expect(page.locator('.mission-heading h2')).toHaveText('검은 선 따라가기');
  await page.getByRole('button',{name:'교사 대시보드'}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
